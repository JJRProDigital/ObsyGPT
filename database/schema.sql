    slug character varying(80) PRIMARY KEY,
    name character varying(150) NOT NULL,
    version character varying(30) DEFAULT '1.0.0' NOT NULL,
    description text DEFAULT '' NOT NULL,
    source character varying(20) DEFAULT 'local' NOT NULL,
