CREATE TABLE public.subagent_dispatches (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_run_id integer NOT NULL REFERENCES public.agent_runs(id) ON DELETE CASCADE,
    child_run_id integer NOT NULL UNIQUE REFERENCES public.agent_runs(id) ON DELETE CASCADE,
    agent_name character varying(100) NOT NULL,
    goal text NOT NULL,
    status character varying(20) DEFAULT 'pending' NOT NULL,
    result text DEFAULT '' NOT NULL,
    created_at timestamp with time zone DEFAULT CURRENT_TIMESTAMP NOT NULL
